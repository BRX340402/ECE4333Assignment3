from pathlib import Path
import gzip
root=Path(__file__).resolve().parents[1]
s=(root/'ESP32_Assignment2/TrafficPage.h').read_text(encoding="utf-8")
page=s.split('R"HTML(',1)[1].split(')HTML";',1)[0].encode()
data=gzip.compress(page,compresslevel=9,mtime=0)
lines=['#pragma once','#include <stdint.h>','// Generated by tools/build_web_page.py; do not edit.','static const uint8_t TRAFFIC_PAGE_GZ[] PROGMEM = {']
lines += [','.join('0x%02x'%v for v in data[i:i+20])+',' for i in range(0,len(data),20)]
lines+=['};','']
(root/'ESP32_Assignment2/TrafficPageGzip.h').write_text('\n'.join(lines), encoding='utf-8')
assert gzip.decompress(data)==page
print(f'HTML {len(page)} bytes -> gzip {len(data)} bytes ({100*len(data)/len(page):.1f}%)')
